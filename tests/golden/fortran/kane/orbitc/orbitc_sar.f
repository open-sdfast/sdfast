C
C Generated TIMESTAMP by SD/FAST, Kane's formulation
C (sdfast 2.0 #10001)
C
C
C These routines are passed to sdroot.
C
      SUBROUTINE SDPOSFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(8),PARAM(1),RESID(1)
C
      INTEGER I
      DOUBLE PRECISION POS(8),VEL(8)
C
      DO 100 I=1,8
        VEL(I)= 0D0
100   CONTINUE
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(1),POS,VEL)
      CALL SDUMOTION(PARAM(1),POS,VEL)
      CALL SDPERR(RESID)
C
      RETURN
      END
C
      SUBROUTINE SDVELFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(8),PARAM(9),RESID(1)
C
C
      CALL SDSTATE(PARAM(9),PARAM,VARS)
      CALL SDUMOTION(PARAM(9),PARAM,VARS)
      CALL SDVERR(RESID)
C
      RETURN
      END
C
      SUBROUTINE SDSTATFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(8),PARAM(9),RESID(9)
C
      DOUBLE PRECISION POS(8),QDOTDUM(8)
C
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(9),POS,PARAM)
      CALL SDUMOTION(PARAM(9),POS,PARAM)
      CALL SDUFORCE(PARAM(9),POS,PARAM)
      CALL SDPERR(RESID)
      CALL SDDERIV(QDOTDUM,RESID(2))
C
      RETURN
      END
C
      SUBROUTINE SDSTDYFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(16),PARAM(1),RESID(10)
C
      DOUBLE PRECISION POS(8),QDOTDUM(8)
C
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(1),POS,VARS(9))
      CALL SDUMOTION(PARAM(1),POS,VARS(9))
      CALL SDUFORCE(PARAM(1),POS,VARS(9))
      CALL SDPERR(RESID)
      CALL SDVERR(RESID(2))
      CALL SDDERIV(QDOTDUM,RESID(3))
C
      RETURN
      END
C
C This routine is passed to the integrator.
C
      SUBROUTINE SDMOTFUNC(TIME,STATE,DSTATE,PARAM,STATUS)
      DOUBLE PRECISION TIME,STATE(16),DSTATE(16),PARAM(1)
      INTEGER STATUS
C
      DOUBLE PRECISION ERR(1)
      INTEGER I
C
      CALL SDSTATE(TIME,STATE,STATE(9))
      CALL SDUMOTION(TIME,STATE,STATE(9))
      CALL SDUFORCE(TIME,STATE,STATE(9))
      CALL SDDERIV(DSTATE,DSTATE(9))
      STATUS= 1
      CALL SDVERR(ERR)
      DO 100 I=1,1
        IF (DABS(ERR(I)) .GT. PARAM(1)) THEN
          RETURN
        ENDIF
100   CONTINUE
      CALL SDPERR(ERR)
      DO 200 I=1,1
        IF (DABS(ERR(I)) .GT. PARAM(1)) THEN
          RETURN
        ENDIF
200   CONTINUE
      STATUS= 0
C
      RETURN
      END
C
C This routine performs assembly analysis.
C
      SUBROUTINE SDASSEMBLE(TIME,STATE,LOCK,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(16)
      INTEGER LOCK(8)
      DOUBLE PRECISION TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION PERRS(1),PARAM(1)
      INTEGER I
      EXTERNAL SDPOSFUNC
      DOUBLE PRECISION JW(8),DW(162),RW(79)
      INTEGER IW(36),ROOTERR
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(50,42)
      ENDIF
      PARAM(1)= TIME
      CALL SDROOT(SDPOSFUNC,STATE,PARAM,1,8,0,LOCK,TOL,TOL,MAXEVALS,
     & JW,DW,RW,IW,PERRS,FCNT,ROOTERR)
      CALL SDPOSFUNC(STATE,PARAM,PERRS)
      FCNT= FCNT+1
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs initial velocity analysis.
C
      SUBROUTINE SDINITVEL(TIME,STATE,LOCK,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(16)
      INTEGER LOCK(8)
      DOUBLE PRECISION TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION VERRS(1),PARAM(9)
      INTEGER I
      EXTERNAL SDVELFUNC
      DOUBLE PRECISION JW(8),DW(162),RW(79)
      INTEGER IW(36),ROOTERR
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(51,42)
      ENDIF
      DO 100 I=1,8
        PARAM(I)= STATE(I)
100   CONTINUE
      PARAM(9)= TIME
      CALL SDROOT(SDVELFUNC,STATE(9),PARAM,1,8,0,LOCK,TOL,TOL,MAXEVALS,
     & JW,DW,RW,IW,VERRS,FCNT,ROOTERR)
      CALL SDVELFUNC(STATE(9),PARAM,VERRS)
      FCNT= FCNT+1
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs static analysis.
C
      SUBROUTINE SDSTATIC(TIME,STATE,LOCK,CTOL,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(16)
      INTEGER LOCK(8)
      DOUBLE PRECISION CTOL,TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION RESID(9),PARAM(9),JW(72),DW(578),RW(135)
      INTEGER IW(68),ROOTERR,I
      EXTERNAL SDSTATFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(52,42)
      ENDIF
      DO 100 I=1,8
        PARAM(I)= STATE(8+I)
100   CONTINUE
      PARAM(9)= TIME
      CALL SDROOT(SDSTATFUNC,STATE,PARAM,9,8,8,LOCK,
     & CTOL,TOL,MAXEVALS,JW,DW,RW,IW,RESID,FCNT,ROOTERR)
      CALL SDSTATFUNC(STATE,PARAM,RESID)
      FCNT= FCNT+1
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs steady motion analysis.
C
      SUBROUTINE SDSTEADY(TIME,STATE,LOCK,CTOL,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(16)
      INTEGER LOCK(16)
      DOUBLE PRECISION CTOL,TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION RESID(10),PARAM(1)
      DOUBLE PRECISION JW(160),DW(1352),RW(214)
      INTEGER IW(104),ROOTERR,I
      EXTERNAL SDSTDYFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(53,42)
      ENDIF
      PARAM(1)= TIME
      CALL SDROOT(SDSTDYFUNC,STATE,PARAM,10,16,8,LOCK,
     & CTOL,TOL,MAXEVALS,JW,DW,RW,IW,RESID,FCNT,ROOTERR)
      CALL SDSTDYFUNC(STATE,PARAM,RESID)
      FCNT= FCNT+1
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs state integration.
C
      SUBROUTINE SDMOTION(TIME,STATE,DSTATE,DT,CTOL,TOL,FLAG,ERR)
      DOUBLE PRECISION TIME,STATE(16),DSTATE(16),DT,CTOL,TOL
      INTEGER FLAG,ERR
C
      DOUBLE PRECISION STEP
      DOUBLE PRECISION WORK(96),TTIME,PARAM(1)
      INTEGER VINTGERR,WHICH,FERR,I
      EXTERNAL SDMOTFUNC
      DATA STEP/0D0/
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(54,42)
      ENDIF
      PARAM(1)= CTOL
      TTIME= TIME
      IF (FLAG .NE. 0) THEN
        CALL SDMOTFUNC(TTIME,STATE,DSTATE,PARAM,FERR)
        STEP= DT
        FLAG= 0
      ENDIF
      IF (STEP .LE. 0D0) THEN
        STEP= DT
      ENDIF
      CALL SDVINTEG(SDMOTFUNC,TTIME,STATE,DSTATE,PARAM,DT,STEP,16,TOL,
     & WORK,VINTGERR,WHICH)
      TIME= TTIME
      ERR= VINTGERR
C
      RETURN
      END
C
C This routine performs state integration with a fixed-step integrator.
C
      SUBROUTINE SDFMOTION(TIME,STATE,DSTATE,DT,CTOL,FLAG,ERREST,ERR)
      DOUBLE PRECISION TIME,STATE(16),DSTATE(16),DT,CTOL
      INTEGER FLAG
      DOUBLE PRECISION ERREST
      INTEGER ERR
C
      DOUBLE PRECISION WORK(64),TTIME,PARAM(1)
      INTEGER FERR,I
      EXTERNAL SDMOTFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(55,42)
      ENDIF
      PARAM(1)= CTOL
      ERR= 0
      TTIME= TIME
      IF (FLAG .NE. 0) THEN
        CALL SDMOTFUNC(TTIME,STATE,DSTATE,PARAM,FERR)
        FLAG= 0
      ENDIF
      CALL SDFINTEG(SDMOTFUNC,TTIME,STATE,DSTATE,PARAM,DT,16,
     & WORK,ERREST,FERR)
      IF (FERR .NE. 0) THEN
        ERR= 1
      ENDIF
      TIME= TTIME
C
      RETURN
      END
