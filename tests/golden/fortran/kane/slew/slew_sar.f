C
C Generated TIMESTAMP by SD/FAST, Kane's formulation
C (sdfast 2.0 #10001)
C
C
C These routines are passed to sdroot.
C
      SUBROUTINE SDPOSFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(11),PARAM(1),RESID(1)
C
      INTEGER I
      DOUBLE PRECISION POS(12),VEL(11)
C
      DO 100 I=1,11
        VEL(I)= 0D0
100   CONTINUE
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(1),POS,VEL)
      CALL SDUMOTION(PARAM(1),POS,VEL)
      CALL SDPERR(RESID)
C
      RETURN
      END
C
      SUBROUTINE SDVELFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(11),PARAM(13),RESID(1)
C
C
      CALL SDSTATE(PARAM(13),PARAM,VARS)
      CALL SDUMOTION(PARAM(13),PARAM,VARS)
      CALL SDVERR(RESID)
C
      RETURN
      END
C
      SUBROUTINE SDSTATFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(11),PARAM(12),RESID(12)
C
      DOUBLE PRECISION POS(12),QDOTDUM(12)
C
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(12),POS,PARAM)
      CALL SDUMOTION(PARAM(12),POS,PARAM)
      CALL SDUFORCE(PARAM(12),POS,PARAM)
      CALL SDPERR(RESID)
      CALL SDDERIV(QDOTDUM,RESID(2))
C
      RETURN
      END
C
      SUBROUTINE SDSTDYFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(22),PARAM(1),RESID(13)
C
      DOUBLE PRECISION POS(12),QDOTDUM(12)
C
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(1),POS,VARS(12))
      CALL SDUMOTION(PARAM(1),POS,VARS(12))
      CALL SDUFORCE(PARAM(1),POS,VARS(12))
      CALL SDPERR(RESID)
      CALL SDVERR(RESID(2))
      CALL SDDERIV(QDOTDUM,RESID(3))
C
      RETURN
      END
C
C This routine is passed to the integrator.
C
      SUBROUTINE SDMOTFUNC(TIME,STATE,DSTATE,PARAM,STATUS)
      DOUBLE PRECISION TIME,STATE(23),DSTATE(23),PARAM(1)
      INTEGER STATUS
C
      DOUBLE PRECISION ERR(1)
      INTEGER I
C
      CALL SDSTATE(TIME,STATE,STATE(13))
      CALL SDUMOTION(TIME,STATE,STATE(13))
      CALL SDUFORCE(TIME,STATE,STATE(13))
      CALL SDDERIV(DSTATE,DSTATE(13))
      STATUS= 1
      CALL SDVERR(ERR)
      DO 100 I=1,1
        IF (DABS(ERR(I)) .GT. PARAM(1)) THEN
          RETURN
        ENDIF
100   CONTINUE
      CALL SDPERR(ERR)
      DO 200 I=1,1
        IF (DABS(ERR(I)) .GT. PARAM(1)) THEN
          RETURN
        ENDIF
200   CONTINUE
      STATUS= 0
C
      RETURN
      END
C
C This routine performs assembly analysis.
C
      SUBROUTINE SDASSEMBLE(TIME,STATE,LOCK,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(23)
      INTEGER LOCK(11)
      DOUBLE PRECISION TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION PERRS(1),PARAM(1)
      INTEGER I
      EXTERNAL SDPOSFUNC
      DOUBLE PRECISION JW(11),DW(288),RW(106)
      INTEGER IW(48),ROOTERR
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(50,42)
      ENDIF
      PARAM(1)= TIME
      CALL SDST2ANG(STATE,STATE)
      CALL SDROOT(SDPOSFUNC,STATE,PARAM,1,11,0,LOCK,TOL,TOL,MAXEVALS,
     & JW,DW,RW,IW,PERRS,FCNT,ROOTERR)
      CALL SDPOSFUNC(STATE,PARAM,PERRS)
      FCNT= FCNT+1
      CALL SDANG2ST(STATE,STATE)
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs initial velocity analysis.
C
      SUBROUTINE SDINITVEL(TIME,STATE,LOCK,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(23)
      INTEGER LOCK(11)
      DOUBLE PRECISION TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION VERRS(1),PARAM(13)
      INTEGER I
      EXTERNAL SDVELFUNC
      DOUBLE PRECISION JW(11),DW(288),RW(106)
      INTEGER IW(48),ROOTERR
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(51,42)
      ENDIF
      DO 100 I=1,12
        PARAM(I)= STATE(I)
100   CONTINUE
      PARAM(13)= TIME
      CALL SDROOT(SDVELFUNC,
     & STATE(13),PARAM,1,11,0,LOCK,TOL,TOL,MAXEVALS,
     & JW,DW,RW,IW,VERRS,FCNT,ROOTERR)
      CALL SDVELFUNC(STATE(13),PARAM,VERRS)
      FCNT= FCNT+1
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs static analysis.
C
      SUBROUTINE SDSTATIC(TIME,STATE,LOCK,CTOL,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(23)
      INTEGER LOCK(11)
      DOUBLE PRECISION CTOL,TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION RESID(12),PARAM(12),JW(132),DW(1058),RW(183)
      INTEGER IW(92),ROOTERR,I
      EXTERNAL SDSTATFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(52,42)
      ENDIF
      DO 100 I=1,11
        PARAM(I)= STATE(12+I)
100   CONTINUE
      PARAM(12)= TIME
      CALL SDST2ANG(STATE,STATE)
      CALL SDROOT(SDSTATFUNC,STATE,PARAM,12,11,11,LOCK,
     & CTOL,TOL,MAXEVALS,JW,DW,RW,IW,RESID,FCNT,ROOTERR)
      CALL SDSTATFUNC(STATE,PARAM,RESID)
      FCNT= FCNT+1
      CALL SDANG2ST(STATE,STATE)
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs steady motion analysis.
C
      SUBROUTINE SDSTEADY(TIME,STATE,LOCK,CTOL,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(23)
      INTEGER LOCK(22)
      DOUBLE PRECISION CTOL,TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION RESID(13),PARAM(1),VARS(22)
      DOUBLE PRECISION JW(286),DW(2450),RW(289)
      INTEGER IW(140),ROOTERR,I
      EXTERNAL SDSTDYFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(53,42)
      ENDIF
      PARAM(1)= TIME
      CALL SDST2ANG(STATE,VARS)
      DO 100 I=1,11
        VARS(11+I)= STATE(12+I)
100   CONTINUE
      CALL SDROOT(SDSTDYFUNC,VARS,PARAM,13,22,11,LOCK,
     & CTOL,TOL,MAXEVALS,JW,DW,RW,IW,RESID,FCNT,ROOTERR)
      CALL SDSTDYFUNC(VARS,PARAM,RESID)
      FCNT= FCNT+1
      CALL SDANG2ST(VARS,STATE)
      DO 200 I=1,11
        STATE(12+I)= VARS(11+I)
200   CONTINUE
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs state integration.
C
      SUBROUTINE SDMOTION(TIME,STATE,DSTATE,DT,CTOL,TOL,FLAG,ERR)
      DOUBLE PRECISION TIME,STATE(23),DSTATE(23),DT,CTOL,TOL
      INTEGER FLAG,ERR
C
      DOUBLE PRECISION STEP
      DOUBLE PRECISION WORK(138),TTIME,PARAM(1)
      INTEGER VINTGERR,WHICH,FERR,I
      EXTERNAL SDMOTFUNC
      DATA STEP/0D0/
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(54,42)
      ENDIF
      PARAM(1)= CTOL
      TTIME= TIME
      IF (FLAG .NE. 0) THEN
        CALL SDMOTFUNC(TTIME,STATE,DSTATE,PARAM,FERR)
        STEP= DT
        FLAG= 0
      ENDIF
      IF (STEP .LE. 0D0) THEN
        STEP= DT
      ENDIF
      CALL SDVINTEG(SDMOTFUNC,TTIME,STATE,DSTATE,PARAM,DT,STEP,23,TOL,
     & WORK,VINTGERR,WHICH)
      TIME= TTIME
      ERR= VINTGERR
C
      RETURN
      END
C
C This routine performs state integration with a fixed-step integrator.
C
      SUBROUTINE SDFMOTION(TIME,STATE,DSTATE,DT,CTOL,FLAG,ERREST,ERR)
      DOUBLE PRECISION TIME,STATE(23),DSTATE(23),DT,CTOL
      INTEGER FLAG
      DOUBLE PRECISION ERREST
      INTEGER ERR
C
      DOUBLE PRECISION WORK(92),TTIME,PARAM(1)
      INTEGER FERR,I
      EXTERNAL SDMOTFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(55,42)
      ENDIF
      PARAM(1)= CTOL
      ERR= 0
      TTIME= TIME
      IF (FLAG .NE. 0) THEN
        CALL SDMOTFUNC(TTIME,STATE,DSTATE,PARAM,FERR)
        FLAG= 0
      ENDIF
      CALL SDFINTEG(SDMOTFUNC,TTIME,STATE,DSTATE,PARAM,DT,23,
     & WORK,ERREST,FERR)
      IF (FERR .NE. 0) THEN
        ERR= 1
      ENDIF
      TIME= TTIME
C
      RETURN
      END
