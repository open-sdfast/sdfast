C
C Generated TIMESTAMP by SD/FAST, Kane's formulation
C (sdfast 2.0 #10001)
C
C
C These routines are passed to sdroot.
C
      SUBROUTINE SDPOSFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(4),PARAM(1),RESID(1)
C
      INTEGER I
      DOUBLE PRECISION POS(4),VEL(4)
C
      DO 100 I=1,4
        VEL(I)= 0D0
100   CONTINUE
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(1),POS,VEL)
      CALL SDUMOTION(PARAM(1),POS,VEL)
      CALL SDPERR(RESID)
C
      RETURN
      END
C
      SUBROUTINE SDVELFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(4),PARAM(5),RESID(1)
C
C
      CALL SDSTATE(PARAM(5),PARAM,VARS)
      CALL SDUMOTION(PARAM(5),PARAM,VARS)
      CALL SDVERR(RESID)
C
      RETURN
      END
C
      SUBROUTINE SDSTATFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(4),PARAM(5),RESID(5)
C
      DOUBLE PRECISION POS(4),QDOTDUM(4)
C
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(5),POS,PARAM)
      CALL SDUMOTION(PARAM(5),POS,PARAM)
      CALL SDUFORCE(PARAM(5),POS,PARAM)
      CALL SDPERR(RESID)
      CALL SDDERIV(QDOTDUM,RESID(2))
C
      RETURN
      END
C
      SUBROUTINE SDSTDYFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(8),PARAM(1),RESID(6)
C
      DOUBLE PRECISION POS(4),QDOTDUM(4)
C
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(1),POS,VARS(5))
      CALL SDUMOTION(PARAM(1),POS,VARS(5))
      CALL SDUFORCE(PARAM(1),POS,VARS(5))
      CALL SDPERR(RESID)
      CALL SDVERR(RESID(2))
      CALL SDDERIV(QDOTDUM,RESID(3))
C
      RETURN
      END
C
C This routine is passed to the integrator.
C
      SUBROUTINE SDMOTFUNC(TIME,STATE,DSTATE,PARAM,STATUS)
      DOUBLE PRECISION TIME,STATE(8),DSTATE(8),PARAM(1)
      INTEGER STATUS
C
      DOUBLE PRECISION ERR(1)
      INTEGER I
C
      CALL SDSTATE(TIME,STATE,STATE(5))
      CALL SDUMOTION(TIME,STATE,STATE(5))
      CALL SDUFORCE(TIME,STATE,STATE(5))
      CALL SDDERIV(DSTATE,DSTATE(5))
      STATUS= 1
      CALL SDVERR(ERR)
      DO 100 I=1,1
        IF (DABS(ERR(I)) .GT. PARAM(1)) THEN
          RETURN
        ENDIF
100   CONTINUE
      CALL SDPERR(ERR)
      DO 200 I=1,1
        IF (DABS(ERR(I)) .GT. PARAM(1)) THEN
          RETURN
        ENDIF
200   CONTINUE
      STATUS= 0
C
      RETURN
      END
C
C This routine performs assembly analysis.
C
      SUBROUTINE SDASSEMBLE(TIME,STATE,LOCK,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(8)
      INTEGER LOCK(4)
      DOUBLE PRECISION TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION PERRS(1),PARAM(1)
      INTEGER I
      EXTERNAL SDPOSFUNC
      DOUBLE PRECISION JW(4),DW(50),RW(43)
      INTEGER IW(20),ROOTERR
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(50,42)
      ENDIF
      PARAM(1)= TIME
      CALL SDROOT(SDPOSFUNC,STATE,PARAM,1,4,0,LOCK,TOL,TOL,MAXEVALS,
     & JW,DW,RW,IW,PERRS,FCNT,ROOTERR)
      CALL SDPOSFUNC(STATE,PARAM,PERRS)
      FCNT= FCNT+1
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs initial velocity analysis.
C
      SUBROUTINE SDINITVEL(TIME,STATE,LOCK,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(8)
      INTEGER LOCK(4)
      DOUBLE PRECISION TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION VERRS(1),PARAM(5)
      INTEGER I
      EXTERNAL SDVELFUNC
      DOUBLE PRECISION JW(4),DW(50),RW(43)
      INTEGER IW(20),ROOTERR
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(51,42)
      ENDIF
      DO 100 I=1,4
        PARAM(I)= STATE(I)
100   CONTINUE
      PARAM(5)= TIME
      CALL SDROOT(SDVELFUNC,STATE(5),PARAM,1,4,0,LOCK,TOL,TOL,MAXEVALS,
     & JW,DW,RW,IW,VERRS,FCNT,ROOTERR)
      CALL SDVELFUNC(STATE(5),PARAM,VERRS)
      FCNT= FCNT+1
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs static analysis.
C
      SUBROUTINE SDSTATIC(TIME,STATE,LOCK,CTOL,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(8)
      INTEGER LOCK(4)
      DOUBLE PRECISION CTOL,TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION RESID(5),PARAM(5),JW(20),DW(162),RW(71)
      INTEGER IW(36),ROOTERR,I
      EXTERNAL SDSTATFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(52,42)
      ENDIF
      DO 100 I=1,4
        PARAM(I)= STATE(4+I)
100   CONTINUE
      PARAM(5)= TIME
      CALL SDROOT(SDSTATFUNC,STATE,PARAM,5,4,4,LOCK,
     & CTOL,TOL,MAXEVALS,JW,DW,RW,IW,RESID,FCNT,ROOTERR)
      CALL SDSTATFUNC(STATE,PARAM,RESID)
      FCNT= FCNT+1
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs steady motion analysis.
C
      SUBROUTINE SDSTEADY(TIME,STATE,LOCK,CTOL,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(8)
      INTEGER LOCK(8)
      DOUBLE PRECISION CTOL,TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION RESID(6),PARAM(1)
      DOUBLE PRECISION JW(48),DW(392),RW(114)
      INTEGER IW(56),ROOTERR,I
      EXTERNAL SDSTDYFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(53,42)
      ENDIF
      PARAM(1)= TIME
      CALL SDROOT(SDSTDYFUNC,STATE,PARAM,6,8,4,LOCK,
     & CTOL,TOL,MAXEVALS,JW,DW,RW,IW,RESID,FCNT,ROOTERR)
      CALL SDSTDYFUNC(STATE,PARAM,RESID)
      FCNT= FCNT+1
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs state integration.
C
      SUBROUTINE SDMOTION(TIME,STATE,DSTATE,DT,CTOL,TOL,FLAG,ERR)
      DOUBLE PRECISION TIME,STATE(8),DSTATE(8),DT,CTOL,TOL
      INTEGER FLAG,ERR
C
      DOUBLE PRECISION STEP
      DOUBLE PRECISION WORK(48),TTIME,PARAM(1)
      INTEGER VINTGERR,WHICH,FERR,I
      EXTERNAL SDMOTFUNC
      DATA STEP/0D0/
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(54,42)
      ENDIF
      PARAM(1)= CTOL
      TTIME= TIME
      IF (FLAG .NE. 0) THEN
        CALL SDMOTFUNC(TTIME,STATE,DSTATE,PARAM,FERR)
        STEP= DT
        FLAG= 0
      ENDIF
      IF (STEP .LE. 0D0) THEN
        STEP= DT
      ENDIF
      CALL SDVINTEG(SDMOTFUNC,TTIME,STATE,DSTATE,PARAM,DT,STEP,8,TOL,
     & WORK,VINTGERR,WHICH)
      TIME= TTIME
      ERR= VINTGERR
C
      RETURN
      END
C
C This routine performs state integration with a fixed-step integrator.
C
      SUBROUTINE SDFMOTION(TIME,STATE,DSTATE,DT,CTOL,FLAG,ERREST,ERR)
      DOUBLE PRECISION TIME,STATE(8),DSTATE(8),DT,CTOL
      INTEGER FLAG
      DOUBLE PRECISION ERREST
      INTEGER ERR
C
      DOUBLE PRECISION WORK(32),TTIME,PARAM(1)
      INTEGER FERR,I
      EXTERNAL SDMOTFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(55,42)
      ENDIF
      PARAM(1)= CTOL
      ERR= 0
      TTIME= TIME
      IF (FLAG .NE. 0) THEN
        CALL SDMOTFUNC(TTIME,STATE,DSTATE,PARAM,FERR)
        FLAG= 0
      ENDIF
      CALL SDFINTEG(SDMOTFUNC,TTIME,STATE,DSTATE,PARAM,DT,8,WORK,ERREST,
     & FERR)
      IF (FERR .NE. 0) THEN
        ERR= 1
      ENDIF
      TIME= TTIME
C
      RETURN
      END
