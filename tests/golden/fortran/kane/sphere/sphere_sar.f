C
C Generated TIMESTAMP by SD/FAST, Kane's formulation
C (sdfast 2.0 #10001)
C
C
C These routines are passed to sdroot.
C
      SUBROUTINE SDPOSFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(6),PARAM(1),RESID(3)
C
      INTEGER I
      DOUBLE PRECISION POS(7),VEL(6)
C
      DO 100 I=1,6
        VEL(I)= 0D0
100   CONTINUE
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(1),POS,VEL)
      CALL SDUMOTION(PARAM(1),POS,VEL)
      CALL SDPERR(RESID)
C
      RETURN
      END
C
      SUBROUTINE SDVELFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(6),PARAM(8),RESID(3)
C
C
      CALL SDSTATE(PARAM(8),PARAM,VARS)
      CALL SDUMOTION(PARAM(8),PARAM,VARS)
      CALL SDVERR(RESID)
C
      RETURN
      END
C
      SUBROUTINE SDSTATFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(6),PARAM(7),RESID(9)
C
      DOUBLE PRECISION POS(7),QDOTDUM(7)
C
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(7),POS,PARAM)
      CALL SDUMOTION(PARAM(7),POS,PARAM)
      CALL SDUFORCE(PARAM(7),POS,PARAM)
      CALL SDPERR(RESID)
      CALL SDDERIV(QDOTDUM,RESID(4))
C
      RETURN
      END
C
      SUBROUTINE SDSTDYFUNC(VARS,PARAM,RESID)
      DOUBLE PRECISION VARS(12),PARAM(1),RESID(12)
C
      DOUBLE PRECISION POS(7),QDOTDUM(7)
C
      CALL SDANG2ST(VARS,POS)
      CALL SDSTATE(PARAM(1),POS,VARS(7))
      CALL SDUMOTION(PARAM(1),POS,VARS(7))
      CALL SDUFORCE(PARAM(1),POS,VARS(7))
      CALL SDPERR(RESID)
      CALL SDVERR(RESID(4))
      CALL SDDERIV(QDOTDUM,RESID(7))
C
      RETURN
      END
C
C This routine is passed to the integrator.
C
      SUBROUTINE SDMOTFUNC(TIME,STATE,DSTATE,PARAM,STATUS)
      DOUBLE PRECISION TIME,STATE(13),DSTATE(13),PARAM(1)
      INTEGER STATUS
C
      DOUBLE PRECISION ERR(3)
      INTEGER I
C
      CALL SDSTATE(TIME,STATE,STATE(8))
      CALL SDUMOTION(TIME,STATE,STATE(8))
      CALL SDUFORCE(TIME,STATE,STATE(8))
      CALL SDDERIV(DSTATE,DSTATE(8))
      STATUS= 1
      CALL SDVERR(ERR)
      DO 100 I=1,3
        IF (DABS(ERR(I)) .GT. PARAM(1)) THEN
          RETURN
        ENDIF
100   CONTINUE
      CALL SDPERR(ERR)
      DO 200 I=1,3
        IF (DABS(ERR(I)) .GT. PARAM(1)) THEN
          RETURN
        ENDIF
200   CONTINUE
      STATUS= 0
C
      RETURN
      END
C
C This routine performs assembly analysis.
C
      SUBROUTINE SDASSEMBLE(TIME,STATE,LOCK,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(13)
      INTEGER LOCK(6)
      DOUBLE PRECISION TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION PERRS(3),PARAM(1)
      INTEGER I
      EXTERNAL SDPOSFUNC
      DOUBLE PRECISION JW(18),DW(162),RW(75)
      INTEGER IW(36),ROOTERR
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(50,42)
      ENDIF
      PARAM(1)= TIME
      CALL SDST2ANG(STATE,STATE)
      CALL SDROOT(SDPOSFUNC,STATE,PARAM,3,6,0,LOCK,TOL,TOL,MAXEVALS,
     & JW,DW,RW,IW,PERRS,FCNT,ROOTERR)
      CALL SDPOSFUNC(STATE,PARAM,PERRS)
      FCNT= FCNT+1
      CALL SDANG2ST(STATE,STATE)
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs initial velocity analysis.
C
      SUBROUTINE SDINITVEL(TIME,STATE,LOCK,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(13)
      INTEGER LOCK(6)
      DOUBLE PRECISION TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION VERRS(3),PARAM(8)
      INTEGER I
      EXTERNAL SDVELFUNC
      DOUBLE PRECISION JW(18),DW(162),RW(75)
      INTEGER IW(36),ROOTERR
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(51,42)
      ENDIF
      DO 100 I=1,7
        PARAM(I)= STATE(I)
100   CONTINUE
      PARAM(8)= TIME
      CALL SDROOT(SDVELFUNC,STATE(8),PARAM,3,6,0,LOCK,TOL,TOL,MAXEVALS,
     & JW,DW,RW,IW,VERRS,FCNT,ROOTERR)
      CALL SDVELFUNC(STATE(8),PARAM,VERRS)
      FCNT= FCNT+1
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs static analysis.
C
      SUBROUTINE SDSTATIC(TIME,STATE,LOCK,CTOL,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(13)
      INTEGER LOCK(6)
      DOUBLE PRECISION CTOL,TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION RESID(9),PARAM(7),JW(54),DW(450),RW(117)
      INTEGER IW(60),ROOTERR,I
      EXTERNAL SDSTATFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(52,42)
      ENDIF
      DO 100 I=1,6
        PARAM(I)= STATE(7+I)
100   CONTINUE
      PARAM(7)= TIME
      CALL SDST2ANG(STATE,STATE)
      CALL SDROOT(SDSTATFUNC,STATE,PARAM,9,6,6,LOCK,
     & CTOL,TOL,MAXEVALS,JW,DW,RW,IW,RESID,FCNT,ROOTERR)
      CALL SDSTATFUNC(STATE,PARAM,RESID)
      FCNT= FCNT+1
      CALL SDANG2ST(STATE,STATE)
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs steady motion analysis.
C
      SUBROUTINE SDSTEADY(TIME,STATE,LOCK,CTOL,TOL,MAXEVALS,FCNT,ERR)
      DOUBLE PRECISION TIME,STATE(13)
      INTEGER LOCK(12)
      DOUBLE PRECISION CTOL,TOL
      INTEGER MAXEVALS,FCNT,ERR
C
      DOUBLE PRECISION RESID(12),PARAM(1),VARS(12)
      DOUBLE PRECISION JW(144),DW(1152),RW(192)
      INTEGER IW(96),ROOTERR,I
      EXTERNAL SDSTDYFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(53,42)
      ENDIF
      PARAM(1)= TIME
      CALL SDST2ANG(STATE,VARS)
      DO 100 I=1,6
        VARS(6+I)= STATE(7+I)
100   CONTINUE
      CALL SDROOT(SDSTDYFUNC,VARS,PARAM,12,12,6,LOCK,
     & CTOL,TOL,MAXEVALS,JW,DW,RW,IW,RESID,FCNT,ROOTERR)
      CALL SDSTDYFUNC(VARS,PARAM,RESID)
      FCNT= FCNT+1
      CALL SDANG2ST(VARS,STATE)
      DO 200 I=1,6
        STATE(7+I)= VARS(6+I)
200   CONTINUE
      IF (ROOTERR .EQ. 0) THEN
        ERR= 0
      ELSE
        IF (FCNT .GE. MAXEVALS) THEN
          ERR= 2
        ELSE
          ERR= 1
        ENDIF
      ENDIF
C
      RETURN
      END
C
C This routine performs state integration.
C
      SUBROUTINE SDMOTION(TIME,STATE,DSTATE,DT,CTOL,TOL,FLAG,ERR)
      DOUBLE PRECISION TIME,STATE(13),DSTATE(13),DT,CTOL,TOL
      INTEGER FLAG,ERR
C
      DOUBLE PRECISION STEP
      DOUBLE PRECISION WORK(78),TTIME,PARAM(1)
      INTEGER VINTGERR,WHICH,FERR,I
      EXTERNAL SDMOTFUNC
      DATA STEP/0D0/
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(54,42)
      ENDIF
      PARAM(1)= CTOL
      TTIME= TIME
      IF (FLAG .NE. 0) THEN
        CALL SDMOTFUNC(TTIME,STATE,DSTATE,PARAM,FERR)
        STEP= DT
        FLAG= 0
      ENDIF
      IF (STEP .LE. 0D0) THEN
        STEP= DT
      ENDIF
      CALL SDVINTEG(SDMOTFUNC,TTIME,STATE,DSTATE,PARAM,DT,STEP,13,TOL,
     & WORK,VINTGERR,WHICH)
      TIME= TTIME
      ERR= VINTGERR
C
      RETURN
      END
C
C This routine performs state integration with a fixed-step integrator.
C
      SUBROUTINE SDFMOTION(TIME,STATE,DSTATE,DT,CTOL,FLAG,ERREST,ERR)
      DOUBLE PRECISION TIME,STATE(13),DSTATE(13),DT,CTOL
      INTEGER FLAG
      DOUBLE PRECISION ERREST
      INTEGER ERR
C
      DOUBLE PRECISION WORK(52),TTIME,PARAM(1)
      INTEGER FERR,I
      EXTERNAL SDMOTFUNC
C
      CALL SDGENTIME(I)
      IF (I .NE. TIMESTAMP) THEN
        CALL SDSETERR(55,42)
      ENDIF
      PARAM(1)= CTOL
      ERR= 0
      TTIME= TIME
      IF (FLAG .NE. 0) THEN
        CALL SDMOTFUNC(TTIME,STATE,DSTATE,PARAM,FERR)
        FLAG= 0
      ENDIF
      CALL SDFINTEG(SDMOTFUNC,TTIME,STATE,DSTATE,PARAM,DT,13,
     & WORK,ERREST,FERR)
      IF (FERR .NE. 0) THEN
        ERR= 1
      ENDIF
      TIME= TTIME
C
      RETURN
      END
